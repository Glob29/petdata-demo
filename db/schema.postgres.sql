-- Production-схема PostgreSQL 14+ для Nutrition DB + Breed DB.
-- Демо-версия: db/schema.sqlite.sql.

BEGIN;

CREATE TABLE source (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          TEXT NOT NULL,
    name          TEXT NOT NULL,
    url           TEXT,
    license       TEXT,
    reliability   SMALLINT NOT NULL DEFAULT 3 CHECK (reliability BETWEEN 1 AND 5),
    notes         TEXT
);

CREATE TABLE manufacturer (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE,
    country       TEXT,
    website       TEXT,
    source_id     BIGINT REFERENCES source(id)
);

CREATE TABLE brand (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer_id BIGINT REFERENCES manufacturer(id),
    name            TEXT NOT NULL,
    website         TEXT,
    source_id       BIGINT REFERENCES source(id)
);

CREATE TABLE product (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id          BIGINT NOT NULL REFERENCES brand(id),
    line_name         TEXT,
    name              TEXT NOT NULL,
    name_key          TEXT,
    species           TEXT NOT NULL CHECK (species IN ('dog','cat')),
    life_stage        TEXT CHECK (life_stage IN ('puppy','kitten','adult','senior','all','unknown')),
    size_class        TEXT CHECK (size_class IN ('mini','small','medium','large','giant','all','unknown')),
    form              TEXT CHECK (form IN ('dry','wet','semi_moist','raw','treat','supplement','unknown')),
    completeness      TEXT CHECK (completeness IN ('complete','complementary','mixed','unknown')),
    class             TEXT NOT NULL DEFAULT 'unknown' CHECK (class IN ('economy','premium','super_premium','holistic','unknown')),
    class_source      TEXT,
    class_confidence  NUMERIC(3,2),
    food_per_kg_day   NUMERIC(8,2),
    reference_weight_kg NUMERIC(5,2),
    food_per_kg_basis TEXT,
    food_per_kg_confidence NUMERIC(3,2),
    therapeutic       BOOLEAN NOT NULL DEFAULT FALSE,
    therapeutic_class TEXT,
    market            TEXT NOT NULL DEFAULT 'RU',
    language          TEXT NOT NULL DEFAULT 'ru',
    source_id         BIGINT REFERENCES source(id),
    source_url        TEXT,
    confidence        NUMERIC(3,2) CHECK (confidence BETWEEN 0 AND 1),
    updated_at        TIMESTAMPTZ
);

CREATE INDEX idx_product_species ON product(species, life_stage);
CREATE INDEX idx_product_brand   ON product(brand_id);
CREATE UNIQUE INDEX uq_product_name_key
    ON product (brand_id, name_key, species, form, market)
    WHERE name_key IS NOT NULL;
CREATE INDEX idx_product_gtin    ON product(gtin);

CREATE TABLE product_search (
    product_id BIGINT PRIMARY KEY REFERENCES product(id) ON DELETE CASCADE,
    content    TSVECTOR NOT NULL
);

CREATE INDEX idx_product_search_content ON product_search USING GIN (content);

CREATE TABLE package (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    weight_g    NUMERIC(10,2) NOT NULL CHECK (weight_g > 0),
    pack_count  INTEGER NOT NULL DEFAULT 1,
    gtin        TEXT,
    price       NUMERIC(12,2),
    currency    TEXT,
    region      TEXT,
    retailer    TEXT,
    source_id   BIGINT REFERENCES source(id),
    -- Вес всей упаковки, средняя цена и цена за грамм (считаются db/compute-prices.js).
    total_weight_g   NUMERIC(10,2),
    price_avg        NUMERIC(12,2),
    price_per_g      NUMERIC(12,4),
    price_samples    INTEGER NOT NULL DEFAULT 0,
    price_updated_at TIMESTAMPTZ
);

CREATE TABLE nutrient (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          TEXT NOT NULL UNIQUE,
    name_ru       TEXT NOT NULL,
    name_en       TEXT,
    unit          TEXT NOT NULL,
    category      TEXT NOT NULL,
    default_basis TEXT NOT NULL DEFAULT 'as_fed',
    sort_order    INTEGER NOT NULL DEFAULT 100
);

CREATE TABLE product_nutrient (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    nutrient_id BIGINT NOT NULL REFERENCES nutrient(id),
    amount      NUMERIC(14,4) NOT NULL,
    unit        TEXT NOT NULL,
    basis       TEXT NOT NULL CHECK (basis IN ('as_fed','dm','per_1000_kcal')),
    value_type  TEXT NOT NULL CHECK (value_type IN ('min','max','typical','declared','calculated')),
    method      TEXT,
    source_id   BIGINT REFERENCES source(id),
    source_url  TEXT,
    confidence  NUMERIC(3,2) CHECK (confidence BETWEEN 0 AND 1),
    valid_from  DATE,
    valid_to    DATE
);

CREATE INDEX idx_pn_product ON product_nutrient(product_id);
CREATE UNIQUE INDEX uq_pn ON product_nutrient
    (product_id, nutrient_id, basis, value_type, COALESCE(source_id, 0), COALESCE(valid_from, DATE '1900-01-01'));

CREATE TABLE ingredient (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_ru        TEXT NOT NULL,
    name_en        TEXT,
    parent_id      BIGINT REFERENCES ingredient(id),
    animal_origin  BOOLEAN,
    allergen_group TEXT
);

CREATE INDEX idx_ingredient_parent ON ingredient(parent_id);

CREATE TABLE product_ingredient (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES ingredient(id),
    position      INTEGER,
    percent       NUMERIC(6,2) CHECK (percent BETWEEN 0 AND 100),
    percent_type  TEXT CHECK (percent_type IN ('as_fed','rehydrated','unknown'))
);

CREATE TABLE additive (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    e_number  TEXT,
    name_ru   TEXT NOT NULL,
    name_en   TEXT,
    category  TEXT
);

CREATE TABLE product_additive (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    additive_id BIGINT NOT NULL REFERENCES additive(id),
    amount      NUMERIC(14,4),
    unit        TEXT
);

CREATE TABLE claim (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    claim_type TEXT,
    text       TEXT NOT NULL
);

CREATE TABLE feeding_guide (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    weight_min_kg  NUMERIC(6,2),
    weight_max_kg  NUMERIC(6,2),
    grams_per_day  NUMERIC(8,2),
    note           TEXT
);

CREATE TABLE price_snapshot (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    package_id  BIGINT REFERENCES package(id),
    price       NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    currency    TEXT NOT NULL DEFAULT 'RUB',
    region      TEXT,
    retailer    TEXT,
    url         TEXT,
    observed_at DATE NOT NULL
);

CREATE INDEX idx_price_product ON price_snapshot(product_id);

CREATE TABLE product_quality (
    product_id                 BIGINT PRIMARY KEY REFERENCES product(id) ON DELETE CASCADE,
    protein_source             TEXT,
    animal_protein_percent     NUMERIC(5,2),
    protein_digestibility_pct  NUMERIC(5,2),
    diaas                      NUMERIC(5,2),
    protein_quality_score      NUMERIC(3,2) CHECK (protein_quality_score BETWEEN 0 AND 5),
    notes                      TEXT,
    flags_json                 JSONB
);

CREATE TABLE allergen_group (
    code                  TEXT PRIMARY KEY,
    name_ru               TEXT NOT NULL,
    description           TEXT,
    cross_reactivity_note TEXT,
    source_id             BIGINT REFERENCES source(id)
);

CREATE TABLE protein_source (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            TEXT NOT NULL UNIQUE,
    name_ru         TEXT NOT NULL,
    name_en         TEXT,
    group_code      TEXT NOT NULL REFERENCES allergen_group(code),
    animal_origin   BOOLEAN NOT NULL DEFAULT TRUE,
    is_novel        BOOLEAN NOT NULL DEFAULT FALSE,
    notes           TEXT,
    source_id       BIGINT REFERENCES source(id)
);

CREATE TABLE product_protein_source (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    protein_source_id  BIGINT NOT NULL REFERENCES protein_source(id),
    role               TEXT CHECK (role IN ('primary','secondary','trace')),
    declared_percent   NUMERIC(5,2) CHECK (declared_percent BETWEEN 0 AND 100),
    is_hydrolyzed      BOOLEAN NOT NULL DEFAULT FALSE,
    source_id          BIGINT REFERENCES source(id),
    confidence         NUMERIC(3,2) CHECK (confidence BETWEEN 0 AND 1)
);

CREATE INDEX idx_pps_product ON product_protein_source(product_id);

CREATE TABLE certificate (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT REFERENCES product(id) ON DELETE CASCADE,
    brand_id     BIGINT REFERENCES brand(id),
    scope        TEXT NOT NULL DEFAULT 'brand' CHECK (scope IN ('brand','product','batch')),
    type         TEXT CHECK (type IN ('declaration','vet_certificate','quality','unknown')),
    number       TEXT,
    issuer       TEXT,
    valid_from   DATE,
    valid_to     DATE,
    url          TEXT,
    status       TEXT NOT NULL DEFAULT 'found' CHECK (status IN ('found','not_found','expired','unreadable')),
    notes        TEXT,
    source_id    BIGINT REFERENCES source(id),
    observed_at  DATE NOT NULL
);

CREATE INDEX idx_certificate_product ON certificate(product_id);

CREATE TABLE breed (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species              TEXT NOT NULL CHECK (species IN ('dog','cat')),
    name_ru              TEXT NOT NULL,
    name_en              TEXT,
    fci_group            TEXT,
    origin_country       TEXT,
    size_class           TEXT CHECK (size_class IN ('mini','small','medium','large','giant')),
    height_min_cm        NUMERIC(5,1),
    height_max_cm        NUMERIC(5,1),
    weight_min_kg        NUMERIC(6,2),
    weight_max_kg        NUMERIC(6,2),
    lifespan_min_years   NUMERIC(4,1),
    lifespan_max_years   NUMERIC(4,1),
    coat_type            TEXT,
    coat_length          TEXT CHECK (coat_length IN ('short','medium','long','hairless')),
    grooming_level       TEXT CHECK (grooming_level IN ('low','medium','high')),
    brachycephalic       BOOLEAN NOT NULL DEFAULT FALSE,
    exercise_level       TEXT CHECK (exercise_level IN ('low','medium','high')),
    temperament          TEXT,
    extra_json           JSONB,
    source_id            BIGINT REFERENCES source(id),
    UNIQUE (species, name_ru)
);

CREATE INDEX idx_breed_species ON breed(species, size_class);

CREATE TABLE breed_weight (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    breed_id   BIGINT NOT NULL REFERENCES breed(id) ON DELETE CASCADE,
    sex        TEXT CHECK (sex IN ('male','female','any')),
    age_stage  TEXT CHECK (age_stage IN ('puppy','adult','senior')),
    min_kg     NUMERIC(6,2),
    max_kg     NUMERIC(6,2),
    source_id  BIGINT REFERENCES source(id)
);

CREATE TABLE condition (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        TEXT NOT NULL UNIQUE,
    name_ru     TEXT NOT NULL,
    name_en     TEXT,
    category    TEXT,
    description TEXT
);

CREATE TABLE breed_predisposition (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    breed_id        BIGINT NOT NULL REFERENCES breed(id) ON DELETE CASCADE,
    condition_id    BIGINT NOT NULL REFERENCES condition(id),
    prevalence_text TEXT,
    evidence_level  TEXT NOT NULL CHECK (evidence_level IN ('A','B','C','D')),
    age_of_onset    TEXT,
    source_id       BIGINT REFERENCES source(id),
    notes           TEXT,
    UNIQUE (breed_id, condition_id, source_id)
);

CREATE INDEX idx_predisposition_breed ON breed_predisposition(breed_id);

CREATE TABLE genetic_test (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    breed_id       BIGINT NOT NULL REFERENCES breed(id) ON DELETE CASCADE,
    gene           TEXT,
    mutation       TEXT,
    inheritance    TEXT,
    test_available BOOLEAN NOT NULL DEFAULT FALSE,
    source_id      BIGINT REFERENCES source(id)
);

CREATE TABLE dataset_version (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version     TEXT NOT NULL,
    released_at TIMESTAMPTZ NOT NULL,
    notes       TEXT
);

CREATE TABLE extraction_run (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT REFERENCES product(id),
    source_id      BIGINT REFERENCES source(id),
    url            TEXT NOT NULL,
    fetched_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    http_status    INTEGER,
    parser         TEXT,
    model          TEXT,
    schema_version TEXT,
    status         TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new','parsed','validated','failed','review')),
    confidence     NUMERIC(3,2),
    raw_path       TEXT,
    error          TEXT
);

CREATE INDEX idx_extraction_run_url ON extraction_run(url);

CREATE TABLE product_source_page (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    source_id   BIGINT REFERENCES source(id),
    url         TEXT NOT NULL,
    fetched_at  TIMESTAMPTZ NOT NULL,
    status      TEXT NOT NULL DEFAULT 'parsed' CHECK (status IN ('parsed','validated','failed')),
    UNIQUE (product_id, url)
);

CREATE INDEX idx_product_source_page ON product_source_page(product_id);

CREATE TABLE review_queue (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT REFERENCES product(id) ON DELETE CASCADE,
    reason      TEXT NOT NULL,
    payload     TEXT,
    status      TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','resolved','rejected')),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ
);

COMMIT;
